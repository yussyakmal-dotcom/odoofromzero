    _description = 'YA Packing Final Allocation per Store'
    _order = 'kitchen_code, reference, store_warehouse_id'

    batch_id = fields.Many2one('ya.packing.batch', required=True,
                               readonly=True, ondelete='restrict', index=True)
    line_id = fields.Many2one('ya.packing.batch.line', required=True,
                              readonly=True, ondelete='restrict')
    ro_id = fields.Many2one('ya.store.ro', required=True, readonly=True,
                            ondelete='restrict')
    kitchen_code = fields.Char(readonly=True)
    reference = fields.Char(readonly=True)
    product_id = fields.Many2one('product.product', required=True, readonly=True)
    store_warehouse_id = fields.Many2one('stock.warehouse', required=True,
                                         readonly=True)
    qty_requested = fields.Integer(readonly=True)
    qty_surplus = fields.Integer(readonly=True)
    qty_shortage = fields.Integer(string='Kekurangan', readonly=True)
    qty_allocated = fields.Integer(readonly=True)

    _unique_batch_line_store = models.Constraint(
        'UNIQUE(line_id, store_warehouse_id)',
        'Duplicate store allocation for this MO.',
    )

    @api.model_create_multi
    def create(self, vals_list):
        if not self.env.context.get('ya_create_production_batch'):
            raise UserError(_('Create allocations only through Packing release.'))
        return super().create(vals_list)

    def write(self, vals):
        raise UserError(_('Final allocation cannot be edited.'))

    def unlink(self):
        raise UserError(_('Pre Produksi allocations cannot be deleted.'))


